def synthetic_development():
    documents, cases = [], []
    for key, title, text, query, history in SCENARIOS:
        if key == "elliptic":
            key, title, text = SCENARIOS[0][:3]
        doc_id = "synthetic-shop:" + key
        if not any(doc.document_id == doc_id for doc in documents):
            documents.append(
                RagDocument(
                    doc_id,
                    title,
                    text,
                    {"synthetic": True, "knowledge_type": "shop_policy"},
                )
            )
        cases.append(
            RagCase(
                "synthetic:" + ("elliptic" if history else key),
                "synthetic:" + key,
                "dev",
                query,
                history,
                (EvidenceSpan(doc_id, 0, len(text), text),),
                ("synthetic_ecommerce",),
            )
        )
    return tuple(documents), tuple(cases)
